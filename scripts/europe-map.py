#!/usr/bin/env python3
"""Generate src/data/europe-outline.ts: SVG outlines of the countries of Europe.

Source: Natural Earth 1:50m admin-0 countries (public domain), e.g.
https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_countries.geojson

Usage: python3 scripts/europe-map.py ne_50m_admin_0_countries.geojson > src/data/europe-outline.ts

One path per country, keyed by its ISO 3166-1 alpha-2 code, so the talks map
can shade the countries I have visited (`countryCode` in src/data/talks.yaml).
The projection (equirectangular, scaled by cos of the central latitude) is
written to the output too, so the map places its markers with exactly the
same formula (see src/components/TalksMap.astro).
"""
import json
import math
import sys

# A wide band (≈ 2.3:1) shown full-bleed with preserveAspectRatio="slice":
# the Atlantic on the left leaves room for the summary laid over the map.
LON_MIN, LON_MAX = -31.0, 39.0
LAT_MIN, LAT_MAX = 34.0, 56.0
WIDTH = 1400
COS = math.cos(math.radians((LAT_MIN + LAT_MAX) / 2))
K = WIDTH / ((LON_MAX - LON_MIN) * COS)
HEIGHT = round((LAT_MAX - LAT_MIN) * K)
PAD = 25  # clip outside the visible box so artificial clip edges stay hidden
TOLERANCE = 0.9  # Douglas–Peucker tolerance, in SVG units


def project(lon, lat):
    return ((lon - LON_MIN) * COS * K, (LAT_MAX - lat) * K)


def clip(poly, xmin, ymin, xmax, ymax):
    """Sutherland–Hodgman clipping of a closed polygon against a rectangle."""
    edges = [
        (lambda p: p[0] >= xmin, lambda a, b: (xmin, a[1] + (b[1] - a[1]) * (xmin - a[0]) / (b[0] - a[0]))),
        (lambda p: p[0] <= xmax, lambda a, b: (xmax, a[1] + (b[1] - a[1]) * (xmax - a[0]) / (b[0] - a[0]))),
        (lambda p: p[1] >= ymin, lambda a, b: (a[0] + (b[0] - a[0]) * (ymin - a[1]) / (b[1] - a[1]), ymin)),
        (lambda p: p[1] <= ymax, lambda a, b: (a[0] + (b[0] - a[0]) * (ymax - a[1]) / (b[1] - a[1]), ymax)),
    ]
    for inside, cut in edges:
        if not poly:
            break
        out = []
        prev = poly[-1]
        for cur in poly:
            if inside(cur):
                if not inside(prev):
                    out.append(cut(prev, cur))
                out.append(cur)
            elif inside(prev):
                out.append(cut(prev, cur))
            prev = cur
        poly = out
    return poly


def simplify(points, tol):
    """Douglas–Peucker on an open polyline."""
    if len(points) < 3:
        return points
    (x1, y1), (x2, y2) = points[0], points[-1]
    dx, dy = x2 - x1, y2 - y1
    norm = math.hypot(dx, dy) or 1e-9
    best, index = 0.0, 0
    for i in range(1, len(points) - 1):
        px, py = points[i]
        d = abs(dy * px - dx * py + x2 * y1 - y2 * x1) / norm
        if d > best:
            best, index = d, i
    if best <= tol:
        return [points[0], points[-1]]
    return simplify(points[: index + 1], tol)[:-1] + simplify(points[index:], tol)


def ring_path(ring):
    """Projected, clipped and simplified SVG path of one ring, or None."""
    pts = [project(lon, lat) for lon, lat in ring]
    pts = clip(pts, -PAD, -PAD, WIDTH + PAD, HEIGHT + PAD)
    if len(pts) < 3:
        return None
    # Split the closed ring at its farthest point from the start, so
    # Douglas–Peucker never sees a zero-length chord.
    far = max(range(len(pts)), key=lambda i: math.dist(pts[0], pts[i]))
    pts = simplify(pts[: far + 1], TOLERANCE)[:-1] + simplify(pts[far:] + [pts[0]], TOLERANCE)[:-1]
    if len(pts) < 3:
        return None
    xs, ys = [p[0] for p in pts], [p[1] for p in pts]
    if (max(xs) - min(xs)) * (max(ys) - min(ys)) < 4:  # drop specks
        return None
    return "M" + "L".join(f"{x:.1f},{y:.1f}" for x, y in pts) + "Z"


def main(path):
    with open(path) as f:
        world = json.load(f)
    countries = []
    for feature in world["features"]:
        props = feature["properties"]
        # ISO_A2 is -99 for a few countries (France, Norway); ISO_A2_EH fills them in.
        code = props.get("ISO_A2_EH") or props.get("ISO_A2")
        geom = feature["geometry"]
        polygons = geom["coordinates"] if geom["type"] == "MultiPolygon" else [geom["coordinates"]]
        # Outer rings only: lakes are not needed at this scale.
        parts = [d for d in (ring_path(polygon[0]) for polygon in polygons) if d]
        if parts:
            countries.append({"code": code if code and code != "-99" else "", "d": "".join(parts)})
    countries.sort(key=lambda c: c["code"])
    print("// Generated by scripts/europe-map.py from Natural Earth 1:50m admin-0 countries (public domain).")
    print("// Do not edit by hand.")
    print(
        "export const EUROPE = "
        + json.dumps(
            {
                "width": WIDTH,
                "height": HEIGHT,
                "lonMin": LON_MIN,
                "latMax": LAT_MAX,
                "cos": round(COS, 6),
                "k": round(K, 6),
                "countries": countries,
            }
        )
        + " as const;"
    )


if __name__ == "__main__":
    main(sys.argv[1])
